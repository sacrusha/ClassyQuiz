"""The root page's examples, from their own .zip files: what the page says of each file, and the face of each.

For every example of the root page's chat (docs/design/root-page.md, "Getting a quiz") in each of its four languages:

- src/client/example-files.ts: the file's name, its size, its title, how many questions it has and its first question,
  read from the .zip in src/public/examples/. The page names the file and its size, and gives the face its accessible
  name from the first question. Generated: edit EXAMPLES here, not that file.
- src/public/landing/face-<example>-<lang>.webp: the file's face, the quiz's first question as the site's Solo screen
  shows it, shot from the site itself (the local check's example, Solo's Play, Start), 800 x 500 CSS px, scaled to
  464 x 290. So the face can't differ from the quiz that plays, and it is a picture: a fetcher reads no quiz words
  between the asks (root-page.md, "One page, two readers"). The site's random draws (the avatar, the choices' order)
  are fixed, so a rebuild draws the same face.

Run from anywhere, after the site is built (cd src && npm run build):
    py -I docs/example/faces.py               the file and the 16 faces
    py -I docs/example/faces.py --files-only  only example-files.ts
It serves src/dist/ itself on a free port; it needs Pillow and playwright, and the installed Edge.
"""
import functools
import http.server
import io
import json
import socketserver
import sys
import threading
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EX = ROOT / "src" / "public" / "examples"
DIST = ROOT / "src" / "dist"
OUT_TS = ROOT / "src" / "client" / "example-files.ts"
OUT_FACES = ROOT / "src" / "public" / "landing"
LANGS = ("en", "de", "fr", "it")

# The examples, in the tabs' order: what the visitor starts from, and the file its example's AI handed over, per language.
# idea: the owner's run (German; the others translated, space_zips.py). sheets: the worked example (English; translated,
# quiz_zips.py). notes: the owner's run (English; translated, notes_zips.py). test: a stand-in until the owner's run
# (mock_zips.py).
EXAMPLES = {
    "idea": {"en": "space-quiz.zip", "de": "weltall-quiz.zip", "fr": "quiz-voyage-espace.zip", "it": "quiz-viaggio-spazio.zip"},
    "sheets": {"en": "big-numbers-quiz.zip", "de": "grosse-zahlen-quiz.zip", "fr": "quiz-grands-nombres.zip", "it": "quiz-grandi-numeri.zip"},
    "notes": {"en": "french-revolution-quiz.zip", "de": "franzoesische-revolution-quiz.zip", "fr": "quiz-revolution-francaise.zip", "it": "quiz-rivoluzione-francese.zip"},
    "test": {"en": "cell-test-practice.zip", "de": "zellen-test-uebung.zip", "fr": "controle-cellule-revision.zip", "it": "verifica-cellula-ripasso.zip"},
}


def read(name):
    path = EX / name
    with zipfile.ZipFile(path) as z:
        text = next(z.read(i) for i in z.infolist() if i.filename.lower().endswith((".txt", ".md"))).decode("utf-8")
    title, numbers, first = "", [], None
    for line in text.split("\n"):
        if line.startswith("Title: ") and not title:
            title = line[7:].strip()
        head = line.split(". ", 1)
        if head[0].isdigit() and (len(head) == 2 or line.rstrip() == head[0] + "."):
            numbers.append(int(head[0]))
            if first is None:
                first = head[1].strip() if len(head) == 2 else ""
    assert numbers == list(range(1, len(numbers) + 1)), f"{name}: questions numbered {numbers}"
    return {"zip": name, "bytes": path.stat().st_size, "title": title, "questions": len(numbers), "first": first}


def write_files():
    data = {ex: {lang: read(files[lang]) for lang in LANGS} for ex, files in EXAMPLES.items()}
    body = json.dumps(data, ensure_ascii=False, indent=2)
    OUT_TS.write_text(
        "// Generated by docs/example/faces.py from the .zip files in src/public/examples/: edit EXAMPLES there and run it.\n"
        "// Per example of the root page's chat and language: the file, its size in bytes, its title, its number of\n"
        "// questions and its first question (docs/design/root-page.md, \"Getting a quiz\").\n\n"
        f"export const EXAMPLE_FILES = {body} as const;\n",
        encoding="utf-8", newline="\n")
    print(OUT_TS)
    return data


class Pages(http.server.SimpleHTTPRequestHandler):
    """dist/ as Pages serves it: /open is open.html."""
    def translate_path(self, path):
        p = super().translate_path(path)
        if not Path(p).exists() and Path(p + ".html").exists():
            return p + ".html"
        return p

    def log_message(self, *a):
        pass


# Math.random, fixed: the avatar Solo gives and the order of the choices come out the same at every build.
SEED = """(() => { let s = 7; Math.random = () => { s = (s * 16807) % 2147483647; return (s - 1) / 2147483646; }; })();"""


def shoot(data):
    from playwright.sync_api import sync_playwright
    from PIL import Image
    if not (DIST / "open.html").exists():
        raise SystemExit("no src/dist/open.html: build the site first (cd src && npm run build)")
    handler = functools.partial(Pages, directory=str(DIST))
    with socketserver.TCPServer(("127.0.0.1", 0), handler) as srv:
        port = srv.server_address[1]
        threading.Thread(target=srv.serve_forever, daemon=True).start()
        with sync_playwright() as p:
            b = p.chromium.launch(channel="msedge")
            for ex in EXAMPLES:
                for lang in LANGS:
                    ctx = b.new_context(viewport={"width": 800, "height": 500}, device_scale_factor=1, color_scheme="light")
                    ctx.add_init_script(SEED)
                    ctx.add_init_script(f"try {{ localStorage.setItem('cq.lang', JSON.stringify('{lang}')); }} catch {{}}")
                    pg = ctx.new_page()
                    errors = []
                    pg.on("pageerror", lambda e: errors.append(str(e)))
                    pg.goto(f"http://127.0.0.1:{port}/open?example={lang}&ex={ex}")
                    pg.wait_for_selector("button[data-entry='0']", timeout=20000)
                    pg.click("button[data-entry='0']")
                    pg.wait_for_selector("[data-solo=start]", timeout=10000)
                    pg.wait_for_timeout(800)  # Solo takes no press in its first moments (SETTLE_MS, client/steps.ts)
                    pg.click("[data-solo=start]")
                    pg.wait_for_timeout(900)
                    pg.evaluate("() => { document.activeElement && document.activeElement.blur(); return Promise.all([...document.images].map((i) => i.decode().catch(() => {}))); }")
                    pg.mouse.move(799, 499)
                    pg.wait_for_timeout(200)
                    png = pg.screenshot()
                    ctx.close()
                    if errors:
                        raise SystemExit(f"{ex} {lang}: {errors}")
                    im = Image.open(io.BytesIO(png)).convert("RGB").resize((464, 290), Image.LANCZOS)
                    out = OUT_FACES / f"face-{ex}-{lang}.webp"
                    im.save(out, "WEBP", quality=86, method=6)
                    print(out.name, out.stat().st_size // 1024, "KB", "·", data[ex][lang]["first"])
            b.close()
        srv.shutdown()


if __name__ == "__main__":
    files = write_files()
    if "--files-only" not in sys.argv[1:]:
        shoot(files)
